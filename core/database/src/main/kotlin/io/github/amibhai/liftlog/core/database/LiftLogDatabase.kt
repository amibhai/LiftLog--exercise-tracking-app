/**
 * The single LiftLog database: built-in exercise library + all user data, so Auto Backup and JSON
 * backups capture everything in one file.
 *
 * Schema changes: bump [VERSION], add a migration to [LiftLogMigrations] with a test, and rebuild
 * the prepopulated asset with tools/exercise-pipeline.
 */
@Database(
    entities = [
        ExerciseEntity::class,
        ExerciseFtsEntity::class,
        ExerciseMuscleEntity::class,
        ExerciseImageEntity::class,
        LibrarySourceEntity::class,
        RoutineEntity::class,
        RoutineExerciseEntity::class,
        ProgramEntity::class,
        ProgramDayEntity::class,
        WorkoutEntity::class,
        WorkoutExerciseEntity::class,
        WorkoutSetEntity::class,
        PersonalRecordEntity::class,
        BodyMetricEntity::class,
        ProgressPhotoEntity::class,
    ],
    version = LiftLogDatabase.VERSION,
    exportSchema = true,
)
abstract class LiftLogDatabase : RoomDatabase() {
    abstract fun exerciseDao(): ExerciseDao

    companion object {
        const val VERSION = 1
        const val NAME = "liftlog.db"

        /** Prepopulated database generated by tools/exercise-pipeline. */
        const val ASSET_PATH = "database/liftlog.db"
    }
}
