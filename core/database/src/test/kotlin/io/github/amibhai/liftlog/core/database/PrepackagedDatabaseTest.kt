import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Opens the asset generated by tools/exercise-pipeline exactly like first launch does
 * (createFromAsset). Room's identity check fails here if the asset is stale for the current schema:
 * rebuild it with `python tools/exercise-pipeline/build_library.py`.
 */
@RunWith(AndroidJUnit4::class)
class PrepackagedDatabaseTest {

    private lateinit var context: Context
    private lateinit var database: LiftLogDatabase
    private lateinit var dao: ExerciseDao

    @Before
    fun setUp() {
        context = ApplicationProvider.getApplicationContext()
        context.deleteDatabase(DB_NAME)
        database = Room.databaseBuilder(context, LiftLogDatabase::class.java, DB_NAME)
            .createFromAsset(LiftLogDatabase.ASSET_PATH)
            .setDriver(AndroidSQLiteDriver())
            .build()
        dao = database.exerciseDao()
    }

    @After
    fun tearDown() {
        database.close()
        context.deleteDatabase(DB_NAME)
    }

    @Test
    fun libraryHasOverOneThousandExercisesThatAllParse() = runTest {
        val exercises = dao.getAll()

        assertThat(exercises.size).isAtLeast(1_000)
        assertThat(dao.observeActiveCount().first()).isEqualTo(exercises.size)
        assertThat(exercises.none { it.isCustom }).isTrue()
        assertThat(exercises.map { it.sourceRef }.distinct()).hasSize(exercises.size)
    }

    @Test
    fun everyExerciseHasAPrimaryMuscle() = runTest {
        val withPrimary = dao.getAllMuscles().filter { it.isPrimary }.map { it.exerciseId }.toSet()

        assertThat(dao.getAll().filterNot { it.id in withPrimary }.map { it.name }).isEmpty()
    }

    @Test
    fun starterSetIsRankedOneToTwelve() = runTest {
        val ranks = dao.getAll().mapNotNull { it.popularityRank }

        assertThat(ranks).containsAtLeastElementsIn(1..STARTER_SET_SIZE)
    }

    @Test
    fun abbreviationsFromTheSpecFindTheRightLift() = runTest {
        assertThat(search("rdl").first()).isEqualTo("Romanian Deadlift")
        assertThat(search("ohp").first()).isEqualTo("Barbell Overhead Press")
        assertThat(search("db bench").first()).isEqualTo("Dumbbell Bench Press")
        assertThat(search("bss").first()).isEqualTo("Bulgarian Split Squat")
        assertThat(search("skullcrusher").first()).isEqualTo("EZ-Bar Skullcrusher")
        assertThat(search("lying triceps extension").first()).isEqualTo("EZ-Bar Skullcrusher")
        assertThat(search("pulldown").first()).isEqualTo("Wide-Grip Lat Pulldown")
        assertThat(search("lat pulldown").first()).isEqualTo("Wide-Grip Lat Pulldown")
    }

    @Test
    fun theCommonLiftComesFirst() = runTest {
        assertThat(search("bench").first()).isEqualTo("Barbell Bench Press")
        assertThat(search("bench press").first()).isEqualTo("Barbell Bench Press")
        assertThat(search("squat").first()).isEqualTo("Barbell Back Squat")
        assertThat(search("deadlift").first()).isEqualTo("Barbell Deadlift")
        assertThat(search("pull up").first()).isEqualTo("Pull-Up")
        assertThat(search("barbell row").first()).isEqualTo("Bent Over Barbell Row")
        assertThat(search("lateral raise").first()).isEqualTo("Side Lateral Raise")
        assertThat(search("chest").first()).isEqualTo("Barbell Bench Press")
        assertThat(search("curl").first()).isEqualTo("Barbell Curl")
        assertThat(search("press").first()).isEqualTo("Barbell Bench Press")
        assertThat(search("lunge").first()).isEqualTo("Dumbbell Lunge")
    }

    @Test
    fun theCatalogHasMusclesAndThumbnails() = runTest {
        val bench = catalog().first { it.name == "Barbell Bench Press" }

        assertThat(bench.primaryMuscles).containsExactly(Muscle.CHEST)
        assertThat(bench.thumbnailUrl).startsWith("https://raw.githubusercontent.com/yuhonas/free-exercise-db/")
    }

    @Test
    fun typosFindTheRightLift() = runTest {
        val index = SearchIndex(catalog())

        assertThat(index.fuzzy("skulcrusher", emptyMap(), limit = 5).first().name).isEqualTo("EZ-Bar Skullcrusher")
        assertThat(index.fuzzy("bnech press", emptyMap(), limit = 5).first().name).isEqualTo("Barbell Bench Press")
        assertThat(index.fuzzy("romainan deadlift", emptyMap(), limit = 5).first().name).isEqualTo("Romanian Deadlift")
    }

    @Test
    fun everyExerciseOfTheBuiltInProgramsExists() = runTest {
        val library = dao.getAll().associateBy { ExerciseId(it.id) }

        for (template in ProgramTemplates.all) {
            for (exercise in template.exercises) {
                assertWithMessage("$exercise in ${template.key}").that(library).containsKey(exercise)
                assertThat(library.getValue(exercise).type.fields).contains(SetField.REPS)
            }
        }
    }

    @Test
    fun theNamesOfOtherAppsFindTheRightLift() = runTest {
        val matcher = ExerciseMatcher(catalog())
        val expected = mapOf(
            "Bench Press (Barbell)" to "Barbell Bench Press",
            "Bench Press (Dumbbell)" to "Dumbbell Bench Press",
            "Incline Bench Press (Barbell)" to "Barbell Incline Bench Press",
            "Squat (Barbell)" to "Barbell Back Squat",
            "Front Squat (Barbell)" to "Barbell Front Squat",
            "Deadlift (Barbell)" to "Barbell Deadlift",
            "Romanian Deadlift (Barbell)" to "Romanian Deadlift",
            "Overhead Press (Barbell)" to "Barbell Overhead Press",
            "Bent Over Row (Barbell)" to "Bent Over Barbell Row",
            "Pull Up" to "Pull-Up",
            "Chin Up" to "Chin-Up",
            "Lat Pulldown (Cable)" to "Wide-Grip Lat Pulldown",
            "Bicep Curl (Barbell)" to "Barbell Curl",
            "Bicep Curl (Dumbbell)" to "Dumbbell Bicep Curl",
            "Hammer Curl (Dumbbell)" to "Hammer Curl",
            "Lateral Raise (Dumbbell)" to "Side Lateral Raise",
            "Leg Press" to "Leg Press",
            "Leg Extension (Machine)" to "Leg Extension",
            "Lying Leg Curl (Machine)" to "Lying Leg Curl",
            "Hip Thrust (Barbell)" to "Barbell Hip Thrust",
            "Triceps Pushdown (Cable)" to "Triceps Pushdown",
            "Face Pull (Cable)" to "Face Pull",
            "Plank" to "Plank",
            "Push Up" to "Push-Up",
        )

        val found = expected.mapValues { (name, _) -> matcher.match(name)?.exercise?.name }
        assertThat(found).isEqualTo(expected)
    }

    @Test
    fun attributionsAreAvailableForTheAboutScreen() = runTest {
        val sources = dao.observeSources().first()

        assertThat(sources.map { it.name }).containsExactly("free-exercise-db", "wger")
        assertThat(sources.sumOf { it.exerciseCount }).isEqualTo(dao.getAll().size)
    }

    private suspend fun search(query: String): List<String> {
        val ids = dao.matchingIds(requireNotNull(FtsQuery.prefix(query))).map(::ExerciseId).toSet()
        return SearchIndex(catalog()).rank(query, ids, emptyMap()).map { it.name }
    }

    private suspend fun catalog(): List<CatalogExercise> {
        val muscles = dao.observePrimaryMuscles().first().groupBy({ it.exerciseId }, { it.muscle })
        val thumbnails = dao.observeThumbnails().first().associate { it.exerciseId to it.url }
        return dao.observeCatalog().first().map { row ->
            CatalogExercise(
                id = ExerciseId(row.id),
                name = row.name,
                aliases = row.aliases.lines().filter(String::isNotBlank),
                searchTerms = row.searchTerms.lines().filter(String::isNotBlank),
                type = row.type,
                equipment = row.equipment,
                primaryMuscles = muscles[row.id].orEmpty(),
                thumbnailUrl = thumbnails[row.id],
                popularityRank = row.popularityRank,
            )
        }
    }

    private companion object {
        const val DB_NAME = "prepackaged-test.db"
        const val STARTER_SET_SIZE = 12
    }
}
