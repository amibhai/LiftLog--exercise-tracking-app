"""Markdown validation report (SPEC §3: counts, duplicates removed, missing fields)."""

from collections import Counter, defaultdict

from .library import LibraryResult
from .normalize import canonical_tokens

LIST_LIMIT = 80
NEAR_DUPLICATE_SIMILARITY = 0.8


def _table(counter: Counter, header: str) -> list[str]:
    lines = [f"| {header} | Count |", "|---|---:|"]
    lines += [f"| {key} | {count} |" for key, count in sorted(counter.items(), key=lambda kv: (-kv[1], str(kv[0])))]
    return lines


def _listing(title: str, header: str, rows: list[str]) -> list[str]:
    lines = [f"## {title} ({len(rows)})", ""]
    if not rows:
        return lines + ["None.", ""]
    columns = header.count("|") - 1
    lines += [header, "|" + "---|" * columns]
    lines += rows[:LIST_LIMIT]
    if len(rows) > LIST_LIMIT:
        lines.append(f"| … {len(rows) - LIST_LIMIT} more |" + " |" * (columns - 1))
    return lines + [""]


def near_duplicates(result: LibraryResult) -> list[tuple[float, str, str, str]]:
    """Pairs with the same equipment whose name tokens mostly overlap; listed for manual review."""
    groups = defaultdict(list)
    for exercise in result.exercises:
        groups[exercise.equipment].append((exercise, set(canonical_tokens(exercise.name))))
    pairs = []
    for members in groups.values():
        for i, (a, tokens_a) in enumerate(members):
            for b, tokens_b in members[i + 1 :]:
                if not tokens_a or not tokens_b:
                    continue
                similarity = len(tokens_a & tokens_b) / len(tokens_a | tokens_b)
                if similarity >= NEAR_DUPLICATE_SIMILARITY:
                    pairs.append((similarity, a.equipment, a.name, b.name))
    return sorted(pairs, key=lambda p: (-p[0], p[2]))


def render(result: LibraryResult, sources: list[dict], config: dict) -> str:
    exercises = result.exercises
    status = "PASSED" if not result.errors else f"FAILED ({len(result.errors)} problems)"
    lines = [
        "# Exercise library report",
        "",
        f"Library version {config['libraryVersion']}: **{len(exercises)} exercises**. "
        "Generated by `tools/exercise-pipeline/build_library.py`; do not edit by hand.",
        "",
        f"**Validation: {status}**",
        "",
        "## Sources",
        "",
    ]
    for source in sources:
        lines.append(
            f"- **{source['name']}** ({source['revision']}): {source['exerciseCount']} exercises kept. "
            f"License: {source['license']}.",
        )
    lines += [
        f"- Input records: {result.source_counts['fedb_input']} from free-exercise-db, "
        f"{result.source_counts['wger_input']} from wger.",
        f"- Duplicates merged: {len(result.duplicates)}. Excluded: {len(result.excluded)}. "
        f"Renamed to resolve name collisions: {len(result.renamed_for_collision)}.",
        "",
    ]

    no_instructions = [e for e in exercises if not e.instructions]
    no_images = [e for e in exercises if not e.images]
    lines += [
        "## Missing fields",
        "",
        f"- No instructions: {len(no_instructions)}",
        f"- No images: {len(no_images)}",
        f"- Muscles inferred from the name (source listed none): {len(result.inferred_muscles)}",
        f"- No mechanic (compound/isolation unknown): {sum(1 for e in exercises if e.mechanic is None)}",
        "",
    ]

    for title, counter, header in (
        ("By exercise type", Counter(e.exercise_type for e in exercises), "Type"),
        ("By equipment", Counter(e.equipment for e in exercises), "Equipment"),
        ("By category", Counter(e.category for e in exercises), "Category"),
        ("By first primary muscle", Counter(e.primary[0] for e in exercises if e.primary), "Muscle"),
        ("By license", Counter(e.license for e in exercises), "License"),
    ):
        lines += [f"## {title}", "", *_table(counter, header), ""]

    if result.errors:
        lines += ["## Problems", "", *[f"- {error}" for error in result.errors], ""]

    lines += _listing(
        "Duplicates merged",
        "| Dropped | Kept |",
        [f"| {name} (`{ref}`) | {kept_name} (`{kept_ref}`) |" for ref, name, kept_ref, kept_name in result.duplicates],
    )
    lines += _listing(
        "Near-duplicates to review",
        "| Similarity | Equipment | Exercise | Exercise |",
        [f"| {s:.2f} | {eq} | {a} | {b} |" for s, eq, a, b in near_duplicates(result)],
    )
    lines += _listing(
        "Excluded",
        "| Exercise | Reason |",
        [f"| {name} (`{ref}`) | {reason} |" for ref, name, reason in result.excluded],
    )
    lines += _listing(
        "Renamed to resolve name collisions",
        "| Before | After |",
        [f"| {old} | {new} |" for _, old, new in result.renamed_for_collision],
    )
    lines += _listing(
        "Muscles inferred from the name",
        "| Exercise | Source |",
        [f"| {name} | `{ref}` |" for ref, name in result.inferred_muscles],
    )
    return "\n".join(lines).rstrip() + "\n"
